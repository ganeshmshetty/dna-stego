"""Frozen low-level primitives shared by the codec and the verifier.

Ownership: lead agent. Do not edit this file from a delegated task.
Every function here is deterministic and side-effect free.
"""

from __future__ import annotations

import random

from reedsolo import RSCodec, ReedSolomonError

from ..config import (
    BASE_TO_BITS,
    BITS_TO_BASE,
    HEADER_BYTES,
    MARK_BYTES,
    PERMUTATION,
    RS_K,
    RS_N,
    RS_PARITY,
    SCRAMBLE_SEED,
    STRAND_LENGTH,
)

_RS = RSCodec(RS_PARITY)


def crc8(data: bytes) -> int:
    """CRC-8/ATM (poly 0x07, init 0x00)."""
    crc = 0
    for byte in data:
        crc ^= byte
        for _ in range(8):
            crc = ((crc << 1) ^ 0x07) & 0xFF if crc & 0x80 else (crc << 1) & 0xFF
    return crc


# --- symbol <-> byte <-> nucleotide ----------------------------------------
def bytes_to_symbols(buf: bytes) -> list[int]:
    """Each byte becomes four 2-bit symbols, most significant first."""
    symbols: list[int] = []
    for byte in buf:
        symbols.extend(((byte >> 6) & 0x03, (byte >> 4) & 0x03, (byte >> 2) & 0x03, byte & 0x03))
    return symbols


def symbols_to_bytes(symbols: list[int]) -> bytes:
    if len(symbols) % 4 != 0:
        raise ValueError("symbol count must be a multiple of 4")
    out = bytearray()
    for i in range(0, len(symbols), 4):
        a, b, c, d = symbols[i : i + 4]
        out.append((a << 6) | (b << 4) | (c << 2) | d)
    return bytes(out)


def symbols_to_nt(symbols: list[int]) -> str:
    return "".join(BITS_TO_BASE[s] for s in symbols)


def nt_to_symbols(nt: str) -> list[int]:
    seq = nt.strip().upper()
    try:
        return [BASE_TO_BITS[b] for b in seq]
    except KeyError as exc:
        raise ValueError(f"non-ACGT base: {exc}") from exc


# --- key-independent scrambler --------------------------------------------
def _scramble_stream(n: int) -> list[int]:
    rng = random.Random(SCRAMBLE_SEED)
    return [rng.randrange(4) for _ in range(n)]


_SCRAMBLE_STREAM = _scramble_stream(STRAND_LENGTH)


def scramble(symbols: list[int]) -> list[int]:
    """Bijective value rotation: out[i] = (in[i] + stream[i]) mod 4."""
    return [(value + _SCRAMBLE_STREAM[i]) % 4 for i, value in enumerate(symbols)]


def unscramble(symbols: list[int]) -> list[int]:
    return [(value - _SCRAMBLE_STREAM[i]) % 4 for i, value in enumerate(symbols)]


# --- fixed position permutation -------------------------------------------
def permute(symbols: list[int]) -> list[int]:
    """out[PERMUTATION[i]] = symbols[i]."""
    if len(symbols) != STRAND_LENGTH:
        raise ValueError(f"expected {STRAND_LENGTH} symbols, got {len(symbols)}")
    out = [0] * STRAND_LENGTH
    for i, value in enumerate(symbols):
        out[PERMUTATION[i]] = value
    return out


def unpermute(symbols: list[int]) -> list[int]:
    """Inverse of permute(): in[i] = symbols[PERMUTATION[i]]."""
    if len(symbols) != STRAND_LENGTH:
        raise ValueError(f"expected {STRAND_LENGTH} symbols, got {len(symbols)}")
    return [symbols[PERMUTATION[i]] for i in range(STRAND_LENGTH)]


# --- Reed-Solomon ----------------------------------------------------------
def rs_encode(data: bytes) -> bytes:
    """34 data bytes -> 50-byte codeword (16 parity bytes appended)."""
    if len(data) != RS_K:
        raise ValueError(f"expected {RS_K} data bytes, got {len(data)}")
    return bytes(_RS.encode(data))


def rs_decode(codeword: bytes) -> bytes | None:
    """50 bytes -> 34 data bytes, or None if uncorrectable."""
    if len(codeword) != RS_N:
        return None
    try:
        decoded, _full, _errata = _RS.decode(codeword)
    except (ReedSolomonError, ValueError):
        return None
    if len(decoded) != RS_K:
        return None
    return bytes(decoded)


# --- data block layout -----------------------------------------------------
def pack_data_block(index: int, payload: bytes, valid_len: int, mark: bytes = b"") -> bytes:
    """Build the 34-byte RS data block.

    `valid_len` is the number of meaningful payload bytes (1..len(payload));
    the final strand is zero-padded to the full payload width.
    """
    mark_bytes = len(mark)
    payload_width = RS_K - HEADER_BYTES - mark_bytes
    if not 0 <= index <= 0xFFFF:
        raise ValueError("strand index must fit in 2 bytes")
    if len(payload) != payload_width:
        raise ValueError(f"payload must be {payload_width} bytes, got {len(payload)}")
    if not 0 <= valid_len <= payload_width:
        raise ValueError(f"valid_len must be in 0..{payload_width}, got {valid_len}")

    data = bytearray(RS_K)
    data[0:2] = index.to_bytes(2, "big")
    data[2] = valid_len
    data[3] = 0
    data[4 : 4 + mark_bytes] = mark
    data[4 + mark_bytes :] = payload
    data[3] = crc8(bytes(data[0:3]) + bytes(data[4:]))
    return bytes(data)


def unpack_data_block(data: bytes, mark_bytes: int = MARK_BYTES) -> tuple[int, int, bytes, bytes] | None:
    """Return (index, valid_len, mark, payload) or None if the CRC fails."""
    if len(data) != RS_K:
        return None
    if data[3] != crc8(data[0:3] + data[4:]):
        return None
    index = int.from_bytes(data[0:2], "big")
    valid_len = data[2]
    payload_width = RS_K - HEADER_BYTES - mark_bytes
    if mark_bytes < 0 or payload_width < 1:
        return None
    if not 0 <= valid_len <= payload_width:
        return None
    mark = bytes(data[4 : 4 + mark_bytes])
    payload = bytes(data[4 + mark_bytes :])
    return index, valid_len, mark, payload


# --- whole-strand helpers --------------------------------------------------
def strand_from_block(data: bytes) -> str:
    """34-byte data block -> 200 nt (RS encode, scramble, permute, map)."""
    codeword = rs_encode(data)
    symbols = bytes_to_symbols(codeword)
    return symbols_to_nt(permute(scramble(symbols)))


def block_from_strand(seq: str) -> bytes | None:
    """200 nt -> 34-byte data block, or None if the strand does not decode."""
    seq = seq.strip().upper()
    if len(seq) != STRAND_LENGTH:
        return None
    try:
        symbols = nt_to_symbols(seq)
    except ValueError:
        return None
    data = symbols_to_bytes(unscramble(unpermute(symbols)))
    return rs_decode(data)


